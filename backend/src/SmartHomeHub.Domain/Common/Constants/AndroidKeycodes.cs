namespace SmartHomeHub.Domain.Common.Constants;

public static class AndroidKeycodes
{
    /// <summary>KEYCODE_WAKEUP — acorda o display sem alterar o estado caso já esteja ligado.</summary>
    public const int WakeUp = 224;

    /// <summary>KEYCODE_HOME — traz o launcher/Google TV para o primeiro plano.</summary>
    public const int Home = 3;

    /// <summary>KEYCODE_POWER — alterna o estado de energia (liga/desliga).</summary>
    public const int Power = 26;
}
